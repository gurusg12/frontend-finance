/* ─────────────────────────────────────────────────────────────────────────────
   Professional report printing.

   How it works: the report is copied into a hidden <div id="print-root"> that sits
   directly under <body>. The print CSS (index.css) hides the whole app and shows only
   that div, using the SAME styles as the screen — so the print looks like the screen,
   just cleaner: company header, period, table borders, signature lines.
   No pop-up window is needed, so it also works on phones and tablets.
───────────────────────────────────────────────────────────────────────────── */
const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

const two = n => String(n).padStart(2, '0');
const stamp = () => {
  const d = new Date();
  return `${two(d.getDate())}/${two(d.getMonth() + 1)}/${d.getFullYear()} ${two(d.getHours())}:${two(d.getMinutes())}`;
};

export function printReport({ element, orgName, title, period, orientation = 'portrait', signatures = true }) {
  if (!element) { window.print(); return; }

  // remove any previous copy
  document.getElementById('print-root')?.remove();
  document.getElementById('print-page-style')?.remove();

  // copy of the report body (without the on-screen title block and without controls)
  const body = element.cloneNode(true);
  body.querySelectorAll('.no-print, [data-screen-header]').forEach(n => n.remove());
  // undo the "fit to phone screen" scaling — print always uses real size
  body.querySelectorAll('[data-fit], [data-fit-inner], [data-fit-sizer]').forEach(n => n.removeAttribute('style'));
  // form controls → plain text so the printout shows the chosen value
  body.querySelectorAll('select').forEach(sel => {
    const span = document.createElement('span');
    span.textContent = sel.options[sel.selectedIndex]?.text || '';
    sel.replaceWith(span);
  });
  body.querySelectorAll('input').forEach(inp => {
    const span = document.createElement('span');
    span.textContent = inp.value;
    inp.replaceWith(span);
  });

  const root = document.createElement('div');
  root.id = 'print-root';
  root.innerHTML = `
    <div class="pr-head">
      <div>
        <div class="pr-org">${esc(orgName)}</div>
        <div class="pr-title">${esc(title)}</div>
      </div>
      <div class="pr-meta">
        ${period ? `<div>${esc(period)}</div>` : ''}
        <div>Printed: ${stamp()}</div>
      </div>
    </div>
    <div class="pr-body"></div>
    ${signatures ? `<div class="pr-sign"><div>Prepared by</div><div>Checked by</div><div>Authorised Signatory</div></div>` : ''}
    <div class="pr-foot">Generated by FinSphere &nbsp;•&nbsp; ${esc(orgName)}</div>`;
  root.querySelector('.pr-body').appendChild(body);
  document.body.appendChild(root);

  // page orientation (wide tables look better in landscape)
  const st = document.createElement('style');
  st.id = 'print-page-style';
  st.textContent = `@page { size: A4 ${orientation === 'landscape' ? 'landscape' : 'portrait'}; margin: 12mm 11mm 16mm; }`;
  document.head.appendChild(st);

  // file name suggested by "Save as PDF"
  const oldTitle = document.title;
  document.title = `${orgName} - ${title}`.replace(/[\\/:*?"<>|]/g, '');

  const cleanup = () => {
    document.title = oldTitle;
    document.getElementById('print-root')?.remove();
    document.getElementById('print-page-style')?.remove();
    window.removeEventListener('afterprint', cleanup);
  };
  window.addEventListener('afterprint', cleanup);

  // small delay so the browser lays the copy out before the print dialog opens
  setTimeout(() => window.print(), 60);
}
